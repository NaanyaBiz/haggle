_CONTRACT = "9999999999"
_GOLDEN = Path(__file__).parent / "fixtures" / "golden_legacy_v050.json"
_ALL_BANDS = ("peak", "offpeak", "shoulder", "normal", "superoffpeak")
_BNE = ZoneInfo("Australia/Brisbane")  # no DST: offsets stable at any date
_ADL = ZoneInfo("Australia/Adelaide")


def _coord(hass: HomeAssistant, tz: ZoneInfo) -> HaggleCoordinator:
    entry = MockConfigEntry(
        domain=DOMAIN,
        data={
            CONF_REFRESH_TOKEN: "v1.testtoken",
            CONF_CONTRACT_NUMBER: _CONTRACT,
            CONF_ACCOUNT_NUMBER: "1234567890",
        },
        options={},
        unique_id="1234567890_9999999999",
    )
    entry.add_to_hass(hass)
    coord = HaggleCoordinator(hass, entry, AsyncMock(), _CONTRACT)
    coord.client.local_tz = tz
    coord.client.tz_is_contract = True
    return coord


def _all_ids() -> list[str]:
    ids = [f"{DOMAIN}:consumption_{_CONTRACT}", f"{DOMAIN}:cost_{_CONTRACT}"]
    for band in _ALL_BANDS:
        ids += [
            f"{DOMAIN}:consumption_{band}_{_CONTRACT}",
            f"{DOMAIN}:cost_{band}_{_CONTRACT}",
        ]
    return ids


def _golden_type(i: int) -> str:
    if 30 <= i < 42:
        return "peak"
    if i < 14:
        return "offpeak"
    return "normal"


def _golden_slot(
    day: date, i: int, rate_type: str, tz: ZoneInfo = _BNE
) -> IntervalReading:
    start = datetime(day.year, day.month, day.day, tzinfo=tz).astimezone(UTC)
    kwh = 0.1 + 0.01 * (i % 7)
    rate = {"peak": 0.5, "offpeak": 0.2, "shoulder": 0.3}.get(rate_type, 0.3)
    return IntervalReading(
        dt=start + timedelta(minutes=30 * i),
        kwh=kwh,
        cost_aud=round(kwh * rate, 6),
        rate_type=rate_type,
    )


def _golden_day(
    day: date, flip: dict[int, str] | None = None, tz: ZoneInfo = _BNE
) -> list[IntervalReading]:
    flip = flip or {}
    return [_golden_slot(day, i, flip.get(i, _golden_type(i)), tz) for i in range(48)]


async def _snapshot(
    hass: HomeAssistant, base: datetime
) -> dict[str, list[list[float]]]:
    snap: dict[str, list[list[float]]] = {}
    for stat_id in _all_ids():
        rows = await _read_series(hass, stat_id)
        key = stat_id.removeprefix(f"{DOMAIN}:").removesuffix(f"_{_CONTRACT}")
        snap[key] = [
            [
                (datetime.fromtimestamp(row["start"], tz=UTC) - base).total_seconds()
                / 3600,
                round(row["state"], 9),
                round(row["sum"], 9),
            ]
            for row in sorted(rows, key=lambda r: r["start"])
        ]
    return snap


def _scenario(key: str) -> str:
    return key.split("/", 1)[0] if "/" in key else ""


def _check_golden(prefix: str, snap: dict[str, list[list[float]]]) -> None:
    """Compare ``snap`` with the fixture's ``prefix`` scenario. With
    HAGGLE_REGEN_GOLDEN=1 (base code ONLY) the scenario is rewritten first,
    leaving the other scenarios in the file untouched."""
    named = {(f"{prefix}/{k}" if prefix else k): rows for k, rows in snap.items()}
    if os.environ.get("HAGGLE_REGEN_GOLDEN") == "1":
        current = json.loads(_GOLDEN.read_text()) if _GOLDEN.exists() else {}
        current = {k: v for k, v in current.items() if _scenario(k) != prefix}
        current.update(named)
        _GOLDEN.write_text(json.dumps(current, indent=0, sort_keys=True) + "\n")
    golden = {
        k: v
        for k, v in json.loads(_GOLDEN.read_text()).items()
        if _scenario(k) == prefix
    }
    assert sorted(named) == sorted(golden)
    # Not vacuous: the scenario wrote band rows, not just the aggregate.
    assert any(rows for k, rows in golden.items() if k.count("_") >= 1)
    for key, rows in golden.items():
        got = named[key]
        assert len(got) == len(rows), (key, len(got), len(rows))
        for want, have in zip(rows, got, strict=True):
            assert want[0] == have[0], (key, want, have)
            assert abs(want[1] - have[1]) < 1e-9, (key, want, have)
            assert abs(want[2] - have[2]) < 1e-9, (key, want, have)


# --- Brisbane: direct imports --------------------------------------------------


async def _golden_scenario(hass: HomeAssistant) -> tuple[datetime, HaggleCoordinator]:
    """Four legacy imports on a never-configured entry (fill active)."""
    today = datetime.now(_BNE).date()
    d0 = today - timedelta(days=12)
    coord = _coord(hass, _BNE)
    base = datetime(d0.year, d0.month, d0.day, tzinfo=_BNE).astimezone(UTC)

    # A: four clean typed days (peak opens the legacy gate from the batch).
    days_a = [d0 + timedelta(days=n) for n in range(4)]
    await coord._import_intervals(
        [r for d in days_a for r in _golden_day(d)],
        known_bands=frozenset(),
        reading_days=set(days_a),
    )
    await async_wait_recording_done(hass)

    # B: a rewindow over D0+1..D0+2 with AGL TYPE FLIPS (peak->normal,
    # normal->shoulder), and D0+3's own fetch ERRORED — but D0+2's response
    # carried D0+3's first two slots as trailing slack, re-typed offpeak->peak.
    d1, d2, d3 = d0 + timedelta(days=1), d0 + timedelta(days=2), d0 + timedelta(days=3)
    batch_b = (
        _golden_day(d1, {30: "normal", 31: "normal", 32: "normal", 33: "normal"})
        + _golden_day(d2, {20: "shoulder", 21: "shoulder"})
        + [_golden_slot(d3, 0, "peak"), _golden_slot(d3, 1, "peak")]
    )
    known = frozenset(await coord._get_stored_tou_bands())
    await coord._import_intervals(batch_b, known_bands=known, reading_days={d1, d2})
    await async_wait_recording_done(hass)

    # C: later all-"normal" days; the stored peak rows keep the gate open,
    # so the normal band is written and the others are re-chained empty.
    days_c = [d0 + timedelta(days=5), d0 + timedelta(days=6)]
    known = frozenset(await coord._get_stored_tou_bands())
    await coord._import_intervals(
        [r for d in days_c for r in _golden_day(d, dict.fromkeys(range(48), "normal"))],
        known_bands=known,
        reading_days=set(days_c),
    )
    await async_wait_recording_done(hass)

    # D: gate CLOSED (no known bands, batch all normal): aggregate only.
    d8 = d0 + timedelta(days=8)
    await coord._import_intervals(
        _golden_day(d8, dict.fromkeys(range(48), "normal")),
        known_bands=frozenset(),
        reading_days={d8},
    )
    await async_wait_recording_done(hass)
    return base, coord


async def test_ac5_never_configured_entry_matches_v050_golden(
    recorder_mock, hass: HomeAssistant
) -> None:
    """AC5, Brisbane. Not vacuous: import B's trailing-slack slots on the
    errored day D0+3 are re-typed offpeak->peak, which v0.5.0 handles by
    carrying the stored offpeak row forward (D0+3 is not authoritative) —
    the partition-exact band fill would zero it; import D's closed gate
    would open under a widened legacy gate (stored normal / BAND_VOCAB)."""
    base, _ = await _golden_scenario(hass)
    _check_golden("", await _snapshot(hass, base))


# --- Adelaide: the A4 straddle trim ------------------------------------------------


async def test_ac5_golden_adelaide_straddle(
    recorder_mock, hass: HomeAssistant, freezer
) -> None:
    """AC5, Adelaide. Local midnight is :30 past the UTC hour, so every batch
    below opens on the contract-local 00:00 slot and the straddle trim drops
    its first bucket in every series. Import B re-imports D1..D2 with type
    flips on both sides of the D1 straddle (D0 23:30 peak in the stored row,
    D1 00:00 re-typed shoulder in the trimmed half) plus D3 trailing slack
    on an errored day, so the trim, the baseline at the stored straddle row
    and the legacy band fill are all pinned for a half-hour zone."""
    freezer.move_to("2026-07-25T03:00:00+00:00")  # Adelaide winter: +09:30
    d0 = date(2026, 7, 6)
    coord = _coord(hass, _ADL)
    base = datetime(d0.year, d0.month, d0.day, tzinfo=_ADL).astimezone(UTC)

    days_a = [d0 + timedelta(days=n) for n in range(4)]
    await coord._import_intervals(
        [
            r
            for d in days_a
            for r in _golden_day(d, {47: "peak"} if d == d0 else None, _ADL)
        ],
        known_bands=frozenset(),
        reading_days=set(days_a),
    )
    await async_wait_recording_done(hass)

    d1, d2, d3 = d0 + timedelta(days=1), d0 + timedelta(days=2), d0 + timedelta(days=3)
    batch_b = (
        _golden_day(d1, {0: "shoulder", 1: "shoulder", 30: "normal"}, _ADL)
        + _golden_day(d2, {20: "shoulder", 47: "peak"}, _ADL)
        + [_golden_slot(d3, 0, "peak", _ADL), _golden_slot(d3, 1, "peak", _ADL)]
    )
    known = frozenset(await coord._get_stored_tou_bands())
    await coord._import_intervals(batch_b, known_bands=known, reading_days={d1, d2})
    await async_wait_recording_done(hass)

    # C: a later day that opens on a NON-midnight slot (its 00:00-01:30 slots
    # zero-on-zero filtered): an hh:00 local slot is :30Z too, but the batch
    # owns that bucket outright — no trim.
    d5 = d0 + timedelta(days=5)
    known = frozenset(await coord._get_stored_tou_bands())
    await coord._import_intervals(
        _golden_day(d5, tz=_ADL)[2:], known_bands=known, reading_days={d5}
    )
    await async_wait_recording_done(hass)

    _check_golden("adl", await _snapshot(hass, base))


# --- the real cycle with a #292 realign junction ------------------------------------


async def test_ac5_golden_real_cycle_with_realign_junction(
    recorder_mock, hass: HomeAssistant, freezer
) -> None:
    """AC5 through ``_async_update_data``: a never-configured ToU entry with
    old-convention QLD history, floor in Sydney DST, so the one-off #292
    re-alignment runs and its junction rewrites the hour below the window
    in the aggregate, the cost and every band series (legacy: AGL's type).
    Pins the cycle wiring (band gate from stored + batch types, the
    re-alignment import, the junction picks) on the legacy path."""
    from tests.test_tz_realign_recorder import (
        _cycle,
        _e2e_coordinator,
        _history,
        _seed_old,
    )

    freezer.move_to("2026-11-20T03:00:00+00:00")
    coord, agl = _e2e_coordinator(hass, _BNE)
    agl.tou = True
    today = datetime.now(UTC).date()
    days = _history(today)
    await _seed_old(hass, coord, _BNE, days, tou=True)

    await _cycle(hass, coord)
    await _cycle(hass, coord)  # a second, plain poll on top

    d0 = days[0]
    base = datetime(d0.year, d0.month, d0.day, tzinfo=_BNE).astimezone(UTC)
    _check_golden("cycle", await _snapshot(hass, base))
