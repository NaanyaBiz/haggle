"""AC5 golden (#141): a never-configured entry writes exactly what v0.5.0 wrote.

``tests/fixtures/golden_legacy_v050.json`` holds one snapshot per scenario,
every row of every consumption/cost series (aggregate + all five bands, so a
series CREATED by a legacy-path change fails too), state and sum per hour.
It was generated by THIS module run against the v0.5.0-beta.5 code
(e8b7a73), never by #141 code, with ``HAGGLE_REGEN_GOLDEN=1``:

    git worktree add <scratch> e8b7a73 --detach
    cp tests/test_legacy_golden.py <scratch>/tests/
    (cd <scratch> && HAGGLE_REGEN_GOLDEN=1 uv run pytest tests/test_legacy_golden.py)
    cp <scratch>/tests/fixtures/golden_legacy_v050.json tests/fixtures/

so this module imports nothing #141 added. Never regenerate it from branch
code to make a change pass (tests/fixtures/PROVENANCE.md).

Scenarios (keys in the fixture):
- ``consumption…`` (no prefix): Brisbane, four direct imports with AGL type
  flips, a trailing-slack reading on an errored day, and a closed gate.
- ``adl/…``: Adelaide (half-hour zone) — every batch opens on the local
  00:00 slot, so the A4 straddle trim drops its first bucket; a rewindow
  with type flips and trailing slack re-chains around the stored straddle.
- ``cycle/…``: the REAL cycle (``_async_update_data``) on a never-configured
  ToU entry whose old-convention QLD history (Sydney DST) is re-aligned —
  the #292 realign junction rewrites the hour below its window per band.
"""

